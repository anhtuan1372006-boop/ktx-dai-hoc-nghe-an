def inpaint(img, boxes, ox, oy):
    a = np.array(img.convert('RGB'))[:, :, ::-1].copy()
    mask = np.zeros(a.shape[:2], np.uint8)
    for b in boxes:
        if len(b) == 5:
            x0, y0, x1, y1, _ = b
            mask[max(0,y0-oy):y1-oy, max(0,x0-ox):x1-ox] = 255
            continue
        (x0, y0, x1, y1) = b
        x0, x1 = max(0, x0-ox), min(a.shape[1], x1-ox)
        if x1 <= x0 or y1-oy <= max(0, y0-oy): continue
        y0, y1 = max(0, y0-oy), min(a.shape[0], y1-oy)
        reg = a[y0:y1, x0:x1].astype(int)
        # text = noticeably darker / more saturated than local light background
        lum = reg.mean(axis=2)
        sat = reg.max(axis=2) - reg.min(axis=2)
        m = ((lum < 200) | (sat > 70)).astype(np.uint8) * 255
        mask[y0:y1, x0:x1] = np.maximum(mask[y0:y1, x0:x1], m)
    mask = cv2.dilate(mask, np.ones((7, 7), np.uint8), iterations=2)
    res = cv2.inpaint(a, mask, 9, cv2.INPAINT_TELEA)
    return Image.fromarray(res[:, :, ::-1])

